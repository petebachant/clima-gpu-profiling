"""Build the experiment index from `exp/*` tags.

Every row is read out of git at the tagged commit, so the index is derived rather
than maintained. It cannot drift from what was actually recorded, and it can be
regenerated at any time. Adding an experiment means tagging a commit, not editing
a table.

Writes experiments.md (for humans and the README) and experiments.csv (for the
calkit.io evidence table).
"""

import csv
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MD = ROOT / "experiments.md"
CSV = ROOT / "experiments.csv"


def git(*args):
    r = subprocess.run(
        ["git", *args], cwd=ROOT, capture_output=True, text=True, check=False
    )
    return r.stdout.strip() if r.returncode == 0 else None


def show_json(ref, path):
    """Read a JSON file as of `ref`, or None if it was not present then."""
    raw = git("show", f"{ref}:{path}")
    if not raw:
        return None
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return None


def treatment_summary(t):
    """One phrase naming what this experiment varied.

    `arms_differ_in` is computed by record-treatment.py from actual content, so
    an empty list genuinely means the arms were identical rather than meaning
    nobody wrote it down.
    """
    if t is None:
        return "unrecorded"
    diff = t.get("arms_differ_in")
    if diff == []:
        return "null test (arms identical)"
    if not diff:
        return "unrecorded"
    names = [d.removesuffix(".jl-mod").removesuffix("-mod") for d in diff]
    env = t.get("declared_env") or {}
    caps = sorted(
        {v for stage in env.values() for k, v in stage.items()
         if k == "CLIMA_MAX_REGISTERS_PER_THREAD"}
    )
    suffix = f" (register cap: {', '.join(caps)})" if caps else ""
    return ", ".join(names) + suffix


def num(d, *keys, fmt="{}"):
    """Nested lookup that tolerates schema drift.

    summary.json has changed shape over this project's history -- SYPD was not
    always recorded, and older runs report only the nsys-derived numbers. An
    index spanning that history has to render a blank cell rather than refuse to
    build.
    """
    for k in keys:
        if not isinstance(d, dict) or k not in d:
            return ""
        d = d[k]
    return fmt.format(d) if isinstance(d, (int, float)) else ""


def rows():
    tags = (git("tag", "-l", "exp/*", "--sort=creatordate") or "").splitlines()
    for tag in tags:
        summary = show_json(tag, "results/summary.json")
        treat = show_json(tag, "results/treatment.json")
        sha = git("rev-list", "-n", "1", tag)
        date = git("log", "-1", "--format=%cs", tag)
        subject = git("tag", "-l", "--format=%(contents:subject)", tag) or ""
        yield {
            "experiment": tag.removeprefix("exp/"),
            "date": date or "",
            "treatment": treatment_summary(treat),
            "speedup_pct": num(summary, "speedup_pct", fmt="{:.3f}"),
            "baseline_sypd": num(summary, "baseline", "sypd", fmt="{:.5f}"),
            "mod_sypd": num(summary, "mod", "sypd", fmt="{:.5f}"),
            "commit": (sha or "")[:9],
            "note": subject.replace("\n", " ").strip(),
        }


FIELDS = [
    "experiment", "date", "treatment", "speedup_pct",
    "baseline_sypd", "mod_sypd", "commit", "note",
]


def main():
    data = list(rows())
    if not data:
        print("no exp/* tags found; nothing to index", file=sys.stderr)

    with CSV.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(data)

    lines = [
        "# Experiment index",
        "",
        "Generated by `scripts/build-experiment-index.py` from `exp/*` git tags.",
        "Do not edit by hand -- add an experiment by tagging a commit, then rerun",
        "the script.",
        "",
        "`speedup_pct` is `(mod - baseline) / mod` in SYPD, the convention every",
        "run in this repo's history uses. A null test measures run-to-run",
        "variation, which is the floor any other row has to clear to mean",
        "anything.",
        "",
        "To reproduce a row:",
        "",
        "```sh",
        "git checkout <commit>",
        "git submodule update --init --recursive",
        "calkit run",
        "```",
        "",
        "| " + " | ".join(FIELDS) + " |",
        "|" + "|".join(["---"] * len(FIELDS)) + "|",
    ]
    for r in data:
        lines.append("| " + " | ".join(str(r[k]) for k in FIELDS) + " |")
    MD.write_text("\n".join(lines) + "\n")

    print(f"wrote {MD.relative_to(ROOT)} and {CSV.relative_to(ROOT)} ({len(data)} experiments)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
